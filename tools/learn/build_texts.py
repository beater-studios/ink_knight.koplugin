# Builds ink_knight/data/learn_texts.lua from the texts of the official Lichess app (lichess-org/mobile, GPL-3.0):
# the ones of the learn stages, in English, Portuguese (Brazil) and Spanish. Placeholders such as {param} become %s.
# Usage, from the plugin folder: python3 -I tools/learn/build_texts.py <folder with the .arb files>
import json
import re
import sys

LANGUAGES = [("en", "app_en.arb"), ("pt", "app_pt_BR.arb"), ("es", "app_es.arb")]
OUT = "ink_knight/data/learn_texts.lua"


def wanted(key):
    return (key.startswith("learn") or key == "enPassant") and not key.startswith("@")


def lua_string(text):
    text = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + text + '"'


# Only the texts with a placeholder go through string.format, so only those get "%" doubled.
def convert(text):
    if not re.search(r"\{[A-Za-z0-9_]+\}", text):
        return text
    return re.sub(r"\{[A-Za-z0-9_]+\}", "%s", text.replace("%", "%%"))


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: python3 -I tools/learn/build_texts.py <folder with the .arb files>")
    folder = sys.argv[1]
    texts = {}
    for language, name in LANGUAGES:
        with open(f"{folder}/{name}", encoding="utf-8") as file:
            data = json.load(file)
        texts[language] = {key: convert(value) for key, value in data.items() if wanted(key)}
    keys = sorted(texts["en"])
    for language, _ in LANGUAGES:
        missing = [key for key in keys if key not in texts[language]]
        if missing:
            sys.exit(f"{language}: missing {', '.join(missing)}")
        for key in keys:
            if texts[language][key].count("%s") != texts["en"][key].count("%s"):
                sys.exit(f"{language}: {key} has other placeholders than English")
    lines = [
        "-- Generated by tools/learn/build_texts.py from lichess-org/mobile (GPL-3.0). Do not edit by hand.",
        "return {",
    ]
    for language, _ in LANGUAGES:
        lines.append(f"    {language} = {{")
        for key in keys:
            lines.append(f"        {key} = {lua_string(texts[language][key])},")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines))
    print(f"{OUT}: {len(keys)} texts in {len(LANGUAGES)} languages")


main()
