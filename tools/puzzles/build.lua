-- Builds ink_knight/data/puzzles/<level>.lua from the Lichess puzzle database (lichess_db_puzzle.csv, CC0), read
-- from the standard input, so the whole file never has to be uncompressed on disk.
-- Usage, from the plugin folder: zstd -dc <folder>/lichess_db_puzzle.csv.zst | luajit tools/puzzles/build.lua
-- For each level it keeps the well tested puzzles of its ratings (QUALITY below), orders them by a hash of their id,
-- which is a fixed shuffle, and takes the first ones whose moves are all legal by the plugin's own rules. The same
-- database gives the same files.
package.path = "./?.lua;" .. package.path
local bit = require("bit")
local Chess = require("ink_knight/chess")
local Pack = require("ink_knight/puzzle_pack")

local QUALITY = {
    max_deviation = 80, -- the rating is settled
    min_popularity = 80, -- most players who rated it liked it
    min_plays = 500,
    max_moves = 9, -- the opponent's move and up to 8 more
}
-- More than needed are kept while reading, in case some fail the check of the moves.
local PER_LEVEL = Pack.GENERATED_PER_LEVEL
local KEEP = PER_LEVEL + 400

local function fail(text)
    io.stderr:write(text, "\n")
    os.exit(1)
end

-- FNV-1a, 32 bits: a fixed, well spread order that does not depend on the order of the database. The prime is
-- 2^24 + 403, multiplied in two parts so the product stays exact in a double before it is cut to 32 bits.
local function hash(text)
    local value = bit.tobit(2166136261)
    for index = 1, #text do
        value = bit.bxor(value, text:byte(index))
        value = bit.tobit(value * 403 + bit.lshift(value, 24))
    end
    return bit.band(value, 0x7fffffff)
end

local function level_for(rating)
    for _, level in ipairs(Pack.LEVELS) do
        local range = Pack.RANGES[level]
        if rating >= range[1] and rating <= range[2] then
            return level
        end
    end
end

-- The smallest hashes of each level, kept sorted: { { hash, id, fen, moves, rating }, ... }.
local kept = {}
for _, level in ipairs(Pack.LEVELS) do
    kept[level] = {}
end
local function keep(level, item)
    local list = kept[level]
    if #list >= KEEP and item[1] >= list[#list][1] then
        return
    end
    local at = #list + 1
    while at > 1 and list[at - 1][1] > item[1] do
        at = at - 1
    end
    table.insert(list, at, item)
    if #list > KEEP then
        list[#list] = nil
    end
end

local lines = 0
for line in io.stdin:lines() do
    lines = lines + 1
    if lines == 1 then
        if not line:match("^PuzzleId,FEN,Moves,Rating,RatingDeviation,Popularity,NbPlays,Themes,") then
            fail("unexpected header: " .. line)
        end
    else
        local id, fen, moves, rating, deviation, popularity, plays, themes = line:match("^([^,]*),([^,]*),([^,]*),([^,]*),([^,]*),([^,]*),([^,]*),([^,]*),")
        rating, deviation, popularity, plays = tonumber(rating), tonumber(deviation), tonumber(popularity), tonumber(plays)
        if id and rating and deviation and popularity and plays and deviation <= QUALITY.max_deviation and popularity >= QUALITY.min_popularity
            and plays >= QUALITY.min_plays and not (" " .. themes .. " "):find(" veryLong ", 1, true)
            and id:match("^%w+$") and select(2, moves:gsub("%S+", "")) <= QUALITY.max_moves then
            local level = level_for(rating)
            if level then
                keep(level, { hash(id), id, fen, moves, rating })
            end
        end
    end
end
if lines < 1000 then
    fail("too few lines read: " .. lines)
end

-- Every move must be legal where it is played, by the rules the puzzle screen uses.
local function playable(fen, moves)
    local position = Chess.parse_fen(fen)
    if not position then
        return false
    end
    local count = 0
    for uci in moves:gmatch("%S+") do
        local legal = false
        for _, move in ipairs(Chess.legal_moves(position)) do
            if Chess.move_to_uci(move) == uci then
                legal = true
                position = Chess.play(position, move)
                break
            end
        end
        if not legal then
            return false
        end
        count = count + 1
    end
    return count >= 2
end

for _, level in ipairs(Pack.LEVELS) do
    local out = {
        "-- Generated by tools/puzzles/build.lua from the Lichess puzzle database (CC0). Do not edit by hand.",
        "-- { id, FEN before the opponent's move, the moves (the opponent's first, then the solution), rating }",
        "return {",
    }
    local count, refused = 0, 0
    for _, item in ipairs(kept[level]) do
        if count == PER_LEVEL then
            break
        end
        if playable(item[3], item[4]) then
            count = count + 1
            out[#out + 1] = string.format("    { %q, %q, %q, %d },", item[2], item[3], item[4], item[5])
        else
            refused = refused + 1
        end
    end
    if count < PER_LEVEL then
        fail(string.format("%s: only %d puzzles", level, count))
    end
    out[#out + 1] = "}"
    out[#out + 1] = ""
    local path = Pack.DATA_DIR .. "/" .. level .. ".lua"
    local file = assert(io.open(path, "wb"))
    file:write(table.concat(out, "\n"))
    file:close()
    print(string.format("%s: %d puzzles (%d refused by the rules)", path, count, refused))
end
local manifest = assert(io.open(Pack.DATA_DIR .. "/manifest.lua", "wb"))
manifest:write(Pack.manifest_source(PER_LEVEL))
manifest:close()
print(string.format("%d lines read", lines - 1))
