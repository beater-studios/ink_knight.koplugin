-- Builds ink_knight/data/openings.lua from the list of openings of Lichess (lichess-org/chess-openings, CC0),
-- reading the moves with the rules of the plugin itself, so the positions are the ones it will look up.
-- Usage, from the plugin folder: luajit tools/openings/build.lua <folder with a.tsv to e.tsv>
package.path = "./?.lua;" .. package.path
local Chess = require("ink_knight/chess")

local sources = assert(arg[1], "usage: luajit tools/openings/build.lua <folder with a.tsv to e.tsv>")
local OUT = "ink_knight/data/openings.lua"

local function fail(text)
    io.stderr:write(text, "\n")
    os.exit(1)
end

local names, keys, seen = {}, {}, {}
local max_plies = 0
for _, letter in ipairs({ "a", "b", "c", "d", "e" }) do
    local file = assert(io.open(sources .. "/" .. letter .. ".tsv", "rb"))
    local number = 0
    for line in file:lines() do
        number = number + 1
        local where = letter .. ".tsv:" .. number
        local eco, name, pgn = line:match("^([^\t]*)\t([^\t]*)\t([^\t]*)$")
        if not eco then
            fail(where .. ": not three columns")
        end
        if number == 1 then
            if line ~= "eco\tname\tpgn" then
                fail(where .. ": unexpected header")
            end
        else
            if not eco:match("^[A-E]%d%d$") or not name:match("%S") or name:find("[%c\"\\]") then
                fail(where .. ": unexpected code or name")
            end
            local position = Chess.parse_fen(Chess.START_FEN)
            local plies = 0
            for token in pgn:gmatch("%S+") do
                if not token:match("^%d+%.+$") then
                    local move = Chess.parse_san(position, token)
                    if not move then
                        fail(where .. ": cannot read the move " .. token)
                    end
                    position = Chess.play(position, move)
                    plies = plies + 1
                end
            end
            if plies == 0 then
                fail(where .. ": no moves")
            end
            local key = Chess.epd(position)
            if seen[key] then
                fail(where .. ": same position as " .. seen[key])
            end
            seen[key] = where
            keys[#keys + 1] = key
            names[key] = name
            max_plies = math.max(max_plies, plies)
        end
    end
    file:close()
end

local out = {
    "-- Generated by tools/openings/build.lua from lichess-org/chess-openings (CC0). Do not edit by hand.",
    "return {",
    string.format("    max_plies = %d,", max_plies),
    "    names = {",
}
for _, key in ipairs(keys) do
    out[#out + 1] = string.format("        [%q] = %q,", key, names[key])
end
out[#out + 1] = "    },"
out[#out + 1] = "}"
out[#out + 1] = ""
local file = assert(io.open(OUT, "wb"))
file:write(table.concat(out, "\n"))
file:close()
print(string.format("%s: %d openings, up to %d half moves", OUT, #keys, max_plies))
