-- Puzzles that come in the package, for readers with no account or no network: a selection from the Lichess puzzle
-- database (CC0), one file per level of difficulty in ink_knight/data/puzzles, read only when that level is played.
-- Each entry is { id, fen, moves, rating }: the FEN is the position before the opponent's move, the first of the
-- moves, and the rest are the solution. The repository has 10000 for each level, and each package of the release
-- has the first ones: 1000 in the usual package, 4000 and 10000 in the larger ones (tools/package.sh); manifest.lua
-- says how many. No KOReader here, so the tests and the generator can use it.
local Pack = {}

-- The levels, as the difficulty option names them, with the ratings each one takes. With no account there is no
-- rating to compare with, so the levels are fixed bands.
Pack.LEVELS = { "easiest", "easier", "normal", "harder", "hardest" }
Pack.RANGES = {
    easiest = { 0, 999 },
    easier = { 1000, 1399 },
    normal = { 1400, 1799 },
    harder = { 1800, 2199 },
    hardest = { 2200, 9999 },
}
Pack.GENERATED_PER_LEVEL = 10000
Pack.DATA_DIR = "ink_knight/data/puzzles"

-- Built from the name, so the package check does not take the start of the path for a file of its own; the files
-- are in the package with the rest of ink_knight/.
local MODULE = Pack.DATA_DIR .. "/%s"

local manifest

-- nil when the package has no puzzles, as a copy without these files.
function Pack.per_level()
    if manifest == nil then
        local ok, data = pcall(require, MODULE:format("manifest"))
        manifest = ok and type(data) == "table" and data or false
    end
    return manifest and manifest.per_level or nil
end

function Pack.manifest_source(count)
    return string.format("-- Generated by tools/puzzles/build.lua, and cut by tools/puzzles/trim.lua for a package.\nreturn { per_level = %d }\n", count)
end

function Pack.available()
    return Pack.per_level() ~= nil
end

function Pack.total()
    return (Pack.per_level() or 0) * #Pack.LEVELS
end

-- A level of the larger package takes a few MB once read, so only the one played is read, and release lets them go
-- when the plugin closes.
function Pack.list(level)
    assert(Pack.RANGES[level], "puzzle_pack: unknown level " .. tostring(level))
    return require(MODULE:format(level))
end

function Pack.release()
    for _, level in ipairs(Pack.LEVELS) do
        package.loaded[MODULE:format(level)] = nil
    end
end

-- The side the reader plays: the opponent moves first, so it is the side not to move in the FEN.
function Pack.reader_color(fen)
    return tostring(fen):match("^%S+ w") and "b" or "w"
end

function Pack.prepare(entry, level, index)
    local first, rest = tostring(entry[3]):match("^(%S+)%s*(.*)$")
    local solution = {}
    for uci in (rest or ""):gmatch("%S+") do
        solution[#solution + 1] = uci
    end
    return { id = entry[1], fen = entry[2], played = first, solution = solution, rating = entry[4], pack = level, pack_index = index }
end

-- The puzzle at index of level, or the next one the reader plays with color ("any", "white" or "black"), going
-- round to the start at the end. nil if the level has none.
function Pack.puzzle(level, index, color)
    local list = Pack.list(level)
    local count = #list
    for step = 0, count - 1 do
        local at = (index - 1 + step) % count + 1
        local entry = list[at]
        local reader = Pack.reader_color(entry[2])
        if color ~= "white" and color ~= "black" or (color == "white") == (reader == "w") then
            return Pack.prepare(entry, level, at)
        end
    end
    return nil
end

-- Where the level goes on after the puzzle at index, going round to the start at the end.
function Pack.next_index(level, index)
    return index % #Pack.list(level) + 1
end

return Pack
